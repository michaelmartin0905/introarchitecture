<section class="ia-points" aria-labelledby="ia-pts-h">
  <div class="ia-wrap ia-points__grid">
    <div class="ia-points__intro ia-rise"><p class="ia-tag">03 — Highlights</p><h2 id="ia-pts-h">What a considered plan brings to a space</h2><p class="ia-lede">Good planning is mostly invisible. You notice it as ease — a room that simply works.</p></div>
    <ol>
      <li class="ia-rise"><h3>Clear zones</h3><p>Cooking, dining, resting, working and storing each get a defined place, so activities support each other instead of competing for the same corner.</p></li>
      <li class="ia-rise"><h3>Comfortable movement</h3><p>Walkways, door swings and drawer clearances are planned at real dimensions so the space feels open in daily use, not just in a photograph.</p></li>
      <li class="ia-rise"><h3>Furniture that fits</h3><p>Sofas, beds, desks and tables are drawn to scale before anything is bought or built, reducing guesswork and costly returns.</p></li>
      <li class="ia-rise"><h3>Light in the right place</h3><p>Daylight, task lighting, cove lighting and accent fittings are positioned around how each zone is actually used.</p></li>
      <li class="ia-rise"><h3>Storage that disappears</h3><p>Built-in cabinetry and concealed storage are planned into walls and joinery early, keeping surfaces calm and uncluttered.</p></li>
      <li class="ia-rise"><h3>A shared reference</h3><p>Dimensioned drawings give everyone involved — family, contractor, carpenter, electrician — the same picture to work from.</p></li>
    </ol>
  </div>
</section>

<section class="ia-approach" aria-labelledby="ia-app-h">
  <div class="ia-wrap ia-approach__grid">
    <figure class="ia-approach__media ia-rise" style="margin:0"><img src="assets/images/introarch-marble-media-wall.jpg" alt="Planned living room with marble feature wall, recessed lighting and a low walnut media console" width="736" height="1308" loading="lazy" decoding="async"><figcaption class="ia-cap" style="color:rgba(232,214,190,.7)">Layered lighting planned around a media wall</figcaption></figure>
    <div>
      <p class="ia-tag">04 — Planning approach</p>
      <h2 id="ia-app-h">From first conversation to final drawing</h2>
      <p style="color:rgba(232,214,190,.82)">Each project follows a steady sequence. Every step builds on the last, so decisions are made in the right order and nothing important is left until it is too late to change.</p>
      <ol class="ia-steps">
        <li class="ia-rise"><div><h3>Listening brief</h3><p>Understanding who uses the space, how, and when — routines, habits, belongings and the feeling you want the room to have.</p></div></li>
        <li class="ia-rise"><div><h3>Measured survey</h3><p>Recording walls, openings, ceiling heights, columns, plumbing and electrical points so the plan starts from accurate information.</p></div></li>
        <li class="ia-rise"><div><h3>Zoning &amp; adjacency</h3><p>Deciding which activities belong together, which need separation, and how the zones connect to one another.</p></div></li>
        <li class="ia-rise"><div><h3>Layout options</h3><p>Testing furniture and joinery arrangements to scale, comparing alternatives and refining the strongest one.</p></div></li>
        <li class="ia-rise"><div><h3>Light, storage &amp; services</h3><p>Coordinating lighting positions, switches, sockets and built-in storage with the chosen layout.</p></div></li>
        <li class="ia-rise"><div><h3>Materials &amp; finishes</h3><p>Selecting surfaces and textures that suit the use of each zone, from worktops and flooring to wall cladding.</p></div></li>
        <li class="ia-rise"><div><h3>Drawings to build from</h3><p>Preparing clear, dimensioned plans and elevations that can be shared with the people carrying out the work.</p></div></li>
      </ol>
    </div>
  </div>
</section>

