<section class="ia-prologue" aria-labelledby="ia-pro-h">
  <div class="ia-wrap ia-prologue__grid">
    <div class="ia-rise"><p class="ia-tag">01 — The idea</p><h2 id="ia-pro-h">Interior planning is design you can measure.</h2></div>
    <div class="ia-prologue__body ia-rise">
      <p>Before colours, fabrics or a single light fitting are chosen, a room has to make sense on paper. Interior planning is the stage where that happens: the walls, windows, doors and services you already have are recorded, and the way you want to live or work is translated into a layout that fits them.</p>
      <p>Space planning sits at the heart of that work. It decides how much floor each activity needs, which zones should sit side by side, where a sofa faces, how far a kitchen island sits from the hob, and whether two people can pass in a corridor without turning sideways.</p>
      <p>The result is a set of clear, dimensioned decisions that a homeowner, contractor or furniture maker can follow — and far fewer surprises once work begins.</p>
    </div>
